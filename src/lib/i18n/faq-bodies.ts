const byLocale: Partial<Record<Locale, FaqCopy>> = { hi, gu };

export function localizeFaqs(faqs: Faq[], locale: Locale): Faq[] {
  const map = byLocale[locale];
  if (!map) return faqs;
  return faqs.map((faq) => {
    const localized = map[faq.id];
    if (!localized) return faq;
    return { ...faq, question: localized.question, answer: localized.answer };
  });
}
