const byLocale: Partial<Record<Locale, ArticleOverlayMap>> = { hi, gu };

export function localizeArticle(article: Article, locale: Locale): Article {
  if (locale === "en") return article;
  const overlay = byLocale[locale]?.[article.slug];
  if (!overlay) return article;
  return { ...article, ...overlay };
}

export function localizeArticles(articles: Article[], locale: Locale): Article[] {
  if (locale === "en") return articles;
  return articles.map((article) => localizeArticle(article, locale));
}
